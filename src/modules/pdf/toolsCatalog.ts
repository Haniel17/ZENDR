export function getToolById(id: string): ToolDefinition | undefined {
  return ZENDR_TOOLS.find((t) => t.id === id);
}

export function getToolsBySection(section: 'pdf' | 'image' | 'data'): ToolDefinition[] {
  return ZENDR_TOOLS.filter((t) => t.section === section);
}

export function getToolsByCategory(cat: string): ToolDefinition[] {
  if (cat === 'all') return ZENDR_TOOLS;
  return ZENDR_TOOLS.filter((t) => t.category === cat || t.section === cat);
}
